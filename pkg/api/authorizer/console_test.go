package authorizer_test

import (
	"flag"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"strings"
	"testing"

	"github.com/shellhub-io/shellhub/pkg/api/authorizer"
	"github.com/stretchr/testify/require"
)

var update = flag.Bool("update", false, "rewrite the console's generated permission table")

const consolePermissionsPath = "../../../ui/apps/console/src/utils/permissions.generated.ts"

func TestConsolePermissionsFile(t *testing.T) {
	want := renderConsolePermissions(t, permissionNames(t))

	if *update {
		require.NoError(t, os.WriteFile(consolePermissionsPath, []byte(want), 0o600))

		return
	}

	got, err := os.ReadFile(consolePermissionsPath)
	require.NoError(t, err)
	require.Equal(t, want, string(got), "the console's permission table is stale: run go generate ./pkg/api/authorizer")
}

func permissionNames(t *testing.T) []string {
	t.Helper()

	file, err := parser.ParseFile(token.NewFileSet(), "permissions.go", nil, 0)
	require.NoError(t, err)

	var names []string
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}

		for i, spec := range gen.Specs {
			value, ok := spec.(*ast.ValueSpec)
			require.True(t, ok)

			if i == 0 {
				typ, ok := value.Type.(*ast.Ident)
				require.True(t, ok && typ.Name == "Permission", "the permission block must open with a typed Permission constant")
				require.Len(t, value.Values, 1)
				first, ok := value.Values[0].(*ast.Ident)
				require.True(t, ok && first.Name == "iota", "the first permission must be iota")
			} else {
				require.Nil(t, value.Type, "permission %s must take its value from iota", value.Names[0].Name)
				require.Empty(t, value.Values, "permission %s must take its value from iota", value.Names[0].Name)
			}

			for _, name := range value.Names {
				names = append(names, name.Name)
			}
		}
	}

	require.NotEmpty(t, names)

	return names
}

func renderConsolePermissions(t *testing.T, names []string) string {
	t.Helper()

	var b strings.Builder

	b.WriteString("// Code generated by \"go generate ./pkg/api/authorizer\"; DO NOT EDIT.\n\n")

	b.WriteString("/** A permission the Go authorizer checks, named after its constant in pkg/api/authorizer. */\n")
	b.WriteString("export type Permission =\n")
	for i, name := range names {
		b.WriteString("  | \"" + name + "\"")
		if i == len(names)-1 {
			b.WriteString(";")
		}
		b.WriteString("\n")
	}

	b.WriteString("\n/** The permissions each assignable role holds, as the Go authorizer's Role.Permissions returns them. */\n")
	b.WriteString("export const rolePermissions = {\n")
	for _, role := range authorizer.AssignableRoles() {
		b.WriteString("  " + role.String() + ": [\n")
		for _, permission := range role.Permissions() {
			require.Less(t, int(permission), len(names), "role %s holds a permission missing from permissions.go", role)
			b.WriteString("    \"" + names[permission] + "\",\n")
		}
		b.WriteString("  ],\n")
	}
	b.WriteString("} as const satisfies Record<string, readonly Permission[]>;\n")

	return b.String()
}
