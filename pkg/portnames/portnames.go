// Lookup returns the service name registered for port, or "" when none is.
func Lookup(port int) string {
	return names[port]
}

// LookupString returns the service name for port given as a decimal string, or "" when port is not
// a number or no service is registered for it.
func LookupString(port string) string {
	n, err := strconv.Atoi(port)
	if err != nil {
		return ""
	}

	return Lookup(n)
}

// Override reads "<port> <name>" lines from path into a map the caller lays over the built-in
// names. It returns [ErrRead] joined with the underlying error when path cannot be opened or read,
// and [ErrLine] carrying the line number for a line whose port is not a number or that has no name.
// Either error comes with a nil map.
func Override(path string) (map[int]string, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, errors.Wrap(ErrRead, err)
	}
	defer file.Close()

	overrides := map[int]string{}
	scanner := bufio.NewScanner(file)
	for line := 1; scanner.Scan(); line++ {
		portText, name, found := strings.Cut(strings.TrimSpace(scanner.Text()), " ")
		port, err := strconv.Atoi(portText)
		if !found || err != nil || name == "" {
			return nil, errors.WithData(ErrLine, line)
		}

		overrides[port] = strings.TrimSpace(name)
	}

	if err := scanner.Err(); err != nil {
		return nil, errors.Wrap(ErrRead, err)
	}

	return overrides, nil
}
